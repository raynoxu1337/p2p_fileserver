package com.raynoxu1337.p2pfileserver

import android.content.Context
import java.io.File

/** Generates FileBrowser Quantum's config.yaml from the app settings. */
object FilebrowserConfig {
    /** Local-only port; filebrowser is never exposed on the network directly. */
    const val PORT = 47821

    private fun q(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", " ") + "\""

    fun write(ctx: Context, p: Prefs, dir: File): File {
        val cache = File(ctx.cacheDir, "filebrowser").apply { mkdirs() }
        val yaml = """
            |# Generated by the app on every start; edits here are overwritten.
            |server:
            |  sources:
            |    - path: ${q(p.sharedFolder)}
            |      name: "Phone"
            |      config:
            |        readOnly: ${p.readOnly}
            |        defaultEnabled: true
            |  cacheDir: ${q(cache.path)}
            |  database:
            |    path: ${q(File(dir, "filebrowser.sqlite").path)}
            |  disableUpdateCheck: true
            |  numImageProcessors: 2
            |  logging:
            |    - levels: "info|warning|error"
            |      noColors: true
            |http:
            |  listen: "127.0.0.1"
            |  port: $PORT
            |  baseURL: ${q(p.webBasePath)}
            |auth:
            |  adminUsername: ${q(p.adminUser)}
            |  adminPassword: ${q(p.adminPassword)}
            |  methods:
            |    password:
            |      enabled: true
            |      signup: false
            |frontend:
            |  name: ${q(p.serverName.take(30))}
            |
        """.trimMargin()
        val f = File(dir, "config.yaml")
        f.writeText(yaml)
        return f
    }
}
